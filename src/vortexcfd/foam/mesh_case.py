"""Meshing case files for blockMesh + surfaceFeatureExtract + snappyHexMesh (no Qt, no pyvista).

The keywords follow the ESI v2606 tutorial incompressible/simpleFoam/motorBike
(system/snappyHexMeshDict, system/surfaceFeatureExtractDict) and etc/caseDicts/meshQualityDict.
[NUMERICS-REVIEW] mesh controls and quality limits are meshing numerics.
"""

import re
import shutil
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path

from vortexcfd.core.model import Mesh
from vortexcfd.foam.case_writer import FoamFileSpec
from vortexcfd.foam.dictfile import write_foam_file
from vortexcfd.foam.mesh_estimate import estimate_mesh

Bounds = tuple[float, float, float, float, float, float]  # xmin, xmax, ymin, ymax, zmin, zmax

MARKER_NAME = ".vortexcfd-case"
MARKER_TEXT = "Generated by VortexCFD: files in this directory may be replaced when meshing.\n"
TRI_SURFACE = "constant/triSurface"

# Domain boundary patches: (name, type). "symmetry" is only present with symmetry enabled.
BOUNDARY_PATCH_TYPES = {
    "inlet": "patch",
    "outlet": "patch",
    "sides": "patch",
    "top": "patch",
    "bottom": "patch",
    "symmetry": "symmetryPlane",
}
RESERVED_PATCH_NAMES = frozenset(BOUNDARY_PATCH_TYPES)

# Fraction of a base cell used to place locationInMesh away from any (refined) cell face.
LOCATION_OFFSET = (0.34, 0.41, 0.28)  # >= 0.027 of a cell from every face up to refinement level 4
# snappyHexMesh cell budget (castellatedMeshControls), as in the tutorial.
MAX_LOCAL_CELLS = 1_000_000
MAX_GLOBAL_CELLS = 5_000_000

# meshQualityControls: the values of etc/caseDicts/meshQualityDict plus the tutorial's smoothing.
MESH_QUALITY = {
    "maxNonOrtho": 65,
    "maxBoundarySkewness": 20,
    "maxInternalSkewness": 4,
    "maxConcave": 80,
    "minVol": 1e-13,
    "minTetQuality": 1e-15,
    "minArea": -1,
    "minTwist": 0.02,
    "minDeterminant": 0.001,
    "minFaceWeight": 0.05,
    "minVolRatio": 0.01,
    "minTriangleTwist": -1,
    "minEdgeLength": -1,
    "nSmoothScale": 4,
    "errorReduction": 0.75,
}


class CaseDirectoryNotOursError(FileExistsError):
    """The case directory has files but no VortexCFD marker: it is not safe to regenerate."""


@dataclass(frozen=True)
class MeshCaseInput:
    """Everything the meshing dictionaries depend on (plain data, metres)."""

    domain_bounds: Bounds
    symmetric: bool  # a symmetry plane at y_min
    parts: tuple[str, ...]  # safe, unique patch names (see ``safe_part_names``)
    parts_bounds: Bounds  # union of the parts' bounding boxes
    reference_length: float
    mesh: Mesh
    # First prism-layer thickness (m) for layer_sizing "absolute_yplus" (see foam/yplus.py).
    first_layer_thickness: float | None = None
    # Number of layers for layer_sizing "absolute_yplus" (foam/yplus.plan_layers); mesh.layers is
    # used for relative sizing only.
    layer_count: int | None = None


def safe_part_names(names: Sequence[str]) -> list[str]:
    """Patch/file-safe unique names: [A-Za-z0-9_], never a reserved boundary name.

    A name that is already taken (by an earlier part or a domain boundary) gets the first free
    numeric suffix ``_1``, ``_2``, ... so the result is deterministic."""
    used: set[str] = set(RESERVED_PATCH_NAMES)
    result = []
    for name in names:
        base = re.sub(r"[^A-Za-z0-9_]", "_", name).strip("_") or "part"
        if base[0].isdigit():
            base = f"part_{base}"
        candidate, n = base, 0
        while candidate in used:
            n += 1
            candidate = f"{base}_{n}"
        used.add(candidate)
        result.append(candidate)
    return result


def block_cells(bounds: Bounds, size: float) -> tuple[int, int, int]:
    """Cells of the background block mesh (at least one per direction)."""
    extents = (bounds[1] - bounds[0], bounds[3] - bounds[2], bounds[5] - bounds[4])
    return tuple(max(1, round(e / size)) for e in extents)  # type: ignore[return-value]


def location_in_mesh(domain: Bounds, parts: Bounds, cells: tuple[int, int, int]) -> tuple[float, float, float]:
    """A point inside the domain, outside every part and away from background cell faces.

    It lies upstream of the parts' bounding box (so outside all parts) in the cell column that
    contains the middle of the parts' y and z range, at a fraction of the cell that is not on a
    face of any refinement level.
    """
    point = []
    for axis in range(3):
        lo, hi = domain[2 * axis], domain[2 * axis + 1]
        step = (hi - lo) / cells[axis]
        if axis == 0:
            target = (lo + parts[0]) / 2  # between the inlet and the parts
        else:
            target = (parts[2 * axis] + parts[2 * axis + 1]) / 2
        index = min(cells[axis] - 1, max(0, int((target - lo) / step)))
        point.append(lo + (index + LOCATION_OFFSET[axis]) * step)
    return tuple(point)  # type: ignore[return-value]


def _hex_faces(bounds: Bounds) -> dict[str, list[int]]:
    """Outward-facing vertex loops of the block's faces (vertex numbering of ``block_mesh``)."""
    return {
        "x_min": [0, 4, 7, 3], "x_max": [1, 2, 6, 5],
        "y_min": [0, 1, 5, 4], "y_max": [3, 7, 6, 2],
        "z_min": [0, 3, 2, 1], "z_max": [4, 5, 6, 7],
    }


def block_mesh_dict(inp: MeshCaseInput) -> FoamFileSpec:
    x0, x1, y0, y1, z0, z1 = inp.domain_bounds
    cells = estimate_mesh(inp.domain_bounds, inp.reference_length, inp.mesh).cells
    faces = _hex_faces(inp.domain_bounds)
    patches = [
        ("inlet", ["x_min"]),
        ("outlet", ["x_max"]),
        ("sides", ["y_max"] if inp.symmetric else ["y_min", "y_max"]),
        ("top", ["z_max"]),
        ("bottom", ["z_min"]),
    ]
    if inp.symmetric:
        patches.append(("symmetry", ["y_min"]))
    return FoamFileSpec(content={
        "scale": 1,
        "vertices": [
            [x0, y0, z0], [x1, y0, z0], [x1, y1, z0], [x0, y1, z0],
            [x0, y0, z1], [x1, y0, z1], [x1, y1, z1], [x0, y1, z1],
        ],
        "blocks": ["hex", [0, 1, 2, 3, 4, 5, 6, 7], list(cells), "simpleGrading", [1, 1, 1]],
        "edges": [],
        "boundary": [
            (name, {"type": BOUNDARY_PATCH_TYPES[name], "faces": [faces[f] for f in which]})
            for name, which in patches
        ],
        "mergePatchPairs": [],
    })


def surface_feature_extract_dict(inp: MeshCaseInput) -> FoamFileSpec:
    """One extractFromSurface entry per part STL (includedAngle = 180 - feature angle)."""
    content = {}
    for name in inp.parts:
        content[f"{name}.stl"] = {
            "extractionMethod": "extractFromSurface",
            "includedAngle": 180.0 - inp.mesh.feature_angle,
            "subsetFeatures": {"nonManifoldEdges": False, "openEdges": True},
            "writeObj": False,
        }
    return FoamFileSpec(content=content)


def _layer_sizing(inp: MeshCaseInput) -> dict:
    """Layer size keywords: relative to the local cell, or absolute from the y+ estimate.

    Absolute: relativeSizes false, firstLayerThickness = the estimator's value (with the
    expansion ratio this fixes the other sizes) and minThickness as a fraction of it.
    """
    m = inp.mesh
    if m.layer_sizing == "relative":
        return {"relativeSizes": True, "finalLayerThickness": m.final_layer_thickness,
                "minThickness": m.min_thickness}
    if inp.first_layer_thickness is None:
        raise ValueError("layer_sizing 'absolute_yplus' needs first_layer_thickness")
    h = inp.first_layer_thickness
    return {"relativeSizes": False, "firstLayerThickness": h, "minThickness": m.min_thickness * h}


# Layer iterations with the main quality controls before snappyHexMesh switches to the `relaxed`
# ones. 0 for absolute (y+) layers: the layer addition uses the relaxed controls from its first
# iteration while snapping keeps the main ones (D-045). Relative sizing writes no nRelaxedIter and
# keeps the v2606 default (labelMax: never relaxed), as the tutorial.
RELAXED_AFTER_LAYER_ITER = 0


def _quality_controls(m: Mesh) -> dict:
    """meshQualityControls: the install's meshQualityDict values for every sizing. With absolute (y+)
    layers the face-decomposition tet-quality test is relaxed only in the `relaxed` sub-dictionary
    (minTetQuality -1e30), which the layer addition uses after RELAXED_AFTER_LAYER_ITER (0) iterations: a
    stack of thin, high-aspect layers trips that test on usable meshes, while every other check keeps
    the main values; checkMesh still judges the final mesh. [NUMERICS-REVIEW]"""
    controls = dict(MESH_QUALITY)
    if m.layer_sizing == "absolute_yplus":
        controls["relaxed"] = {"minTetQuality": -1e30}
    return controls


def snappy_hex_mesh_dict(inp: MeshCaseInput) -> FoamFileSpec:
    m = inp.mesh
    est = estimate_mesh(inp.domain_bounds, inp.reference_length, m)
    cells = est.cells
    geometry = {f"{n}.stl": {"type": "triSurfaceMesh", "name": n} for n in inp.parts}
    refinement_surfaces = {
        n: {
            "level": [est.level_min, est.level_max],
            "patchInfo": {"type": "wall", "inGroups": [f"{n}Group"]},
        }
        for n in inp.parts
    }
    n_layers = m.layers
    if m.layer_sizing == "absolute_yplus" and inp.layer_count is not None:
        n_layers = inp.layer_count
    layers = {f'"{n}.*"': {"nSurfaceLayers": n_layers} for n in inp.parts} if n_layers > 0 else {}
    content = {
        "castellatedMesh": True,
        "snap": True,
        "addLayers": n_layers > 0,
        "geometry": geometry,
        "castellatedMeshControls": {
            "maxLocalCells": MAX_LOCAL_CELLS,
            "maxGlobalCells": MAX_GLOBAL_CELLS,
            "minRefinementCells": 10,
            "maxLoadUnbalance": 0.10,
            "nCellsBetweenLevels": 3,
            "features": [{"file": f'"{n}.eMesh"', "level": est.level_max} for n in inp.parts],
            "refinementSurfaces": refinement_surfaces,
            "resolveFeatureAngle": m.feature_angle,
            "refinementRegions": {},
            "locationInMesh": list(location_in_mesh(inp.domain_bounds, inp.parts_bounds, cells)),
            "allowFreeStandingZoneFaces": True,
        },
        "snapControls": {
            "nSmoothPatch": 3,
            "tolerance": 2.0,
            "nSolveIter": 30,
            "nRelaxIter": 5,
            "nFeatureSnapIter": 10,
            "implicitFeatureSnap": False,
            "explicitFeatureSnap": True,
            "multiRegionFeatureSnap": False,
        },
        "addLayersControls": {
            **_layer_sizing(inp),
            "layers": layers,
            "expansionRatio": m.expansion_ratio,
            "nGrow": 0,
            "featureAngle": 60,
            "slipFeatureAngle": 30,
            "nRelaxIter": 3,
            "nSmoothSurfaceNormals": 1,
            "nSmoothNormals": 3,
            "nSmoothThickness": 10,
            "maxFaceThicknessRatio": 0.5,
            "maxThicknessToMedialRatio": 0.3,
            "minMedialAxisAngle": 90,
            "nBufferCellsNoExtrude": 0,
            "nLayerIter": 50,
            **({"nRelaxedIter": RELAXED_AFTER_LAYER_ITER} if m.layer_sizing == "absolute_yplus" else {}),
        },
        "meshQualityControls": _quality_controls(m),
        "mergeTolerance": 1e-6,
    }
    return FoamFileSpec(content=content)


def control_dict() -> FoamFileSpec:
    """Minimal controlDict so the meshing utilities can create a Time object."""
    return FoamFileSpec(content={
        "application": "snappyHexMesh",
        "startFrom": "startTime",
        "startTime": 0,
        "stopAt": "endTime",
        "endTime": 1,
        "deltaT": 1,
        "writeControl": "timeStep",
        "writeInterval": 1,
        "writeFormat": "ascii",
        "writePrecision": 8,
        "timeFormat": "general",
        "timePrecision": 6,
    })


def fv_schemes() -> FoamFileSpec:
    """Placeholder schemes: snappyHexMesh and checkMesh only need the file to exist."""
    return FoamFileSpec(content={
        "ddtSchemes": {"default": "steadyState"},
        "gradSchemes": {"default": ["Gauss", "linear"]},
        "divSchemes": {"default": "none"},
        "laplacianSchemes": {"default": ["Gauss", "linear", "corrected"]},
        "interpolationSchemes": {"default": "linear"},
        "snGradSchemes": {"default": "corrected"},
    })


def fv_solution() -> FoamFileSpec:
    return FoamFileSpec(content={"solvers": {}})


def build_mesh_files(inp: MeshCaseInput) -> dict[str, FoamFileSpec]:
    """All dictionaries needed to mesh: relative path -> spec."""
    files = {
        "system/controlDict": control_dict(),
        "system/fvSchemes": fv_schemes(),
        "system/fvSolution": fv_solution(),
        "system/blockMeshDict": block_mesh_dict(inp),
        "system/snappyHexMeshDict": snappy_hex_mesh_dict(inp),
    }
    if inp.parts:
        files["system/surfaceFeatureExtractDict"] = surface_feature_extract_dict(inp)
    return files


