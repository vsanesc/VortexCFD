# Internal flow has no domain (D-129, QUESTIONS 206): only the background box's and the 2D slab's own patch names are
# reserved, so a region named "inlet" or "outlet" keeps its name.
INTERNAL_RESERVED_PATCH_NAMES = frozenset({BACKGROUND_PATCH, FRONT_PATCH, BACK_PATCH, FRONT_AND_BACK})


def safe_part_names(names: Sequence[str], internal: bool = False) -> list[str]:
    """Patch/file-safe unique names: [A-Za-z0-9_], never a reserved boundary name (``internal``: only the
    background and 2D slab names, INTERNAL_RESERVED_PATCH_NAMES).

    A name that is already taken (by an earlier part or a domain boundary) gets the first free
    numeric suffix ``_1``, ``_2``, ... so the result is deterministic."""
    used: set[str] = set(INTERNAL_RESERVED_PATCH_NAMES if internal else RESERVED_PATCH_NAMES)
    result = []
    for name in names:
        base = re.sub(r"[^A-Za-z0-9_]", "_", name).strip("_") or "part"
        if base[0].isdigit():
            base = f"part_{base}"
        candidate, n = base, 0
        while candidate in used:
            n += 1
            candidate = f"{base}_{n}"
        used.add(candidate)
        result.append(candidate)
    return result


def part_patch_names(parts: Sequence, internal: bool = False) -> list[tuple[str, ...]]:
    """Per part (core.model.Part), its safe wall patch names in Part.patch_names() order.

    Every name of every part goes through ``safe_part_names`` together, so a patch name used by
    two parts becomes two patches (the second gets a suffix); a part without regions has the one
    patch it always had."""
    raw = [part.patch_names() for part in parts]
    safe = safe_part_names([name for names in raw for name in names], internal)
    out, k = [], 0
    for names in raw:
        out.append(tuple(safe[k:k + len(names)]))
        k += len(names)
    return out


def wall_patch_names(parts: Sequence, internal: bool = False) -> tuple[str, ...]:
    """Every part patch of the mesh, in part and region order."""
    return tuple(name for names in part_patch_names(parts, internal) for name in names)


def part_force_groups(parts: Sequence) -> tuple[tuple[str, tuple[str, ...]], ...]:
    """(key, patches) of every part with several patches: its per-part force objects cover ALL its
    patches. The key is the part's safe name; a part whose safe name is also a patch name gets no
    group (that patch keeps the key)."""
    patches = part_patch_names(parts)
    taken = {p for names in patches for p in names}
    return tuple((key, names) for key, names in zip(safe_part_names([p.name for p in parts]), patches)
                 if len(names) > 1 and key not in taken)


def force_report_keys(parts: Sequence) -> tuple[str, ...]:
    """Keys of the per-wall force reports: every patch, then every multi-patch part."""
    return wall_patch_names(parts) + tuple(key for key, _ in part_force_groups(parts))


# snappyHexMesh finds a surface only where a segment between two neighbouring cell centres crosses
# it. Those segments form a lattice of lines spaced one background cell apart, so a convex part is
# certain to be pierced only if its projection along its thinnest axis holds a disc of this many
# background cells in diameter (a disc of diameter sqrt(2) h always contains a lattice point). The
# check uses the part's second-largest bounding-box extent as that diameter (D-052).
SEED_BACKGROUND_CELLS = math.sqrt(2.0)
SEED_EXTENSION = 0.2  # seed lines reach this fraction of the extent beyond the part's box


# Curvature refinement (refinementSurfaces curvatureLevel, v2606: refinementSurfaces.C
# setCurvatureMinLevelFields; tutorial mesh/snappyHexMesh/block_with_curvature): (cells per radius of
# curvature, start level (not used by v2606), maximum level, ignore level (-1: none)). A surface
# triangle gets level round(log2(cells * base / radius)) when that is above its surface level and at
# most the maximum; a radius that would need more than the maximum gets no curvature refinement, and
# points on sharp edges (beyond resolveFeatureAngle) are skipped. 4 cells per radius: about 14 degrees
# of arc per cell. [NUMERICS-REVIEW]
CURVATURE_CELLS_PER_RADIUS = 4


def curvature_level(part_max_level: int, extra_levels: int) -> list[int] | None:
    """The curvatureLevel entry of a part at maximum surface level ``part_max_level``; None when
    curvature refinement is off (D-085)."""
    if extra_levels <= 0:
        return None
    return [CURVATURE_CELLS_PER_RADIUS, 0, part_max_level + extra_levels, -1]


def part_level_range(level_min: int, level_max: int, override: tuple[int | None, int | None]) -> tuple[int, int]:
    """A part's (min, max) surface levels: its overrides, otherwise the mesh's levels. As for the
    mesh, setting only the max gives min = max - 1; setting only the min raises the max to it."""
    lo_o, hi_o = override
    hi = hi_o if hi_o is not None else max(level_max, lo_o if lo_o is not None else 0)
    if lo_o is not None:
        lo = lo_o
    elif hi_o is not None:
        lo = max(hi - 1, 0)
    else:
        lo = level_min
    return min(lo, hi), hi


def min_extent(bounds: Bounds) -> float:
    return min(bounds[1] - bounds[0], bounds[3] - bounds[2], bounds[5] - bounds[4])


def section_extent(bounds: Bounds) -> float:
    """The second-largest extent of a box (the smaller side of its largest projection)."""
    return sorted((bounds[1] - bounds[0], bounds[3] - bounds[2], bounds[5] - bounds[4]))[1]


def needs_seed(bounds: Bounds, base_size: float) -> bool:
    """True when the part may fall between the background cell-centre lines (see
    SEED_BACKGROUND_CELLS)."""
    return section_extent(bounds) < SEED_BACKGROUND_CELLS * base_size


def seed_file_name(part: str) -> str:
    return f"{part}_seed.eMesh"


# A part thinner than this many surface cells (at its maximum level) is also seeded (D-052).
THIN_SURFACE_CELLS = 3.0


def needs_seeding(bounds: Bounds, base_size: float, level_max: int) -> bool:
    """The pre-mesh criterion: the part may fall between the background cell-centre lines
    (needs_seed) or is thinner than THIN_SURFACE_CELLS surface cells at its maximum level."""
    return needs_seed(bounds, base_size) or min_extent(bounds) < THIN_SURFACE_CELLS * base_size / 2 ** level_max


def seeded_parts(inp: "MeshCaseInput", base_size: float, level_min: int, level_max: int) -> list[int]:
    """Indices of the parts that get seed lines automatically: every part flagged by
    needs_seeding at its own levels (overrides if set, otherwise the mesh's). [NUMERICS-REVIEW]"""
    out = []
    if inp.two_d:  # the directional staircases find every section (D-121)
        return out
    for i, bounds in enumerate(inp.part_bounds):
        override = inp.part_levels[i] if i < len(inp.part_levels) else (None, None)
        _lo, hi = part_level_range(level_min, level_max, override)
        if needs_seeding(bounds, base_size, hi):
            out.append(i)
    return out


def seed_edge_mesh_text(part: str, bounds: Bounds) -> str:
    """A featureEdgeMesh with three axis-aligned lines through the centre of the part's box, each
    reaching SEED_EXTENSION of its extent beyond the box. snappyHexMesh's explicit feature refinement
    (which runs before surface refinement and needs no surface intersection) refines the cells along
    them, so the part's surface is then found by the finer cells."""
    centre = [(bounds[2 * a] + bounds[2 * a + 1]) / 2 for a in range(3)]
    points = []
    for axis in range(3):
        half = (bounds[2 * axis + 1] - bounds[2 * axis]) / 2 * (1 + SEED_EXTENSION)
        for sign in (-1, 1):
            p = list(centre)
            p[axis] += sign * half
            points.append(p)
    rows = "\n".join(f"({x:.9g} {y:.9g} {z:.9g})" for x, y, z in points)
    return (
        "FoamFile\n{\n    version     2.0;\n    format      ascii;\n    class       featureEdgeMesh;\n"
        f"    object      {seed_file_name(part)};\n}}\n"
        f"// Seed lines for part {part} (VortexCFD, D-052)\n"
        f"6\n(\n{rows}\n)\n3\n(\n(0 1)\n(2 3)\n(4 5)\n)\n"
    )


def write_seed_edge_meshes(case_dir: Path, inp: "MeshCaseInput") -> list[str]:
    """Write the seed eMesh of every seeded part into constant/triSurface; returns the part names."""
    est = inp.estimate()
    names = []
    for i in seeded_parts(inp, est.base_size, est.level_min, est.level_max):
        name = inp.parts[i]
        (Path(case_dir) / TRI_SURFACE / seed_file_name(name)).write_text(
            seed_edge_mesh_text(name, inp.part_bounds[i]), encoding="utf-8")
        names.append(name)
    return names


def block_cells(bounds: Bounds, size: float) -> tuple[int, int, int]:
    """Cells of the background block mesh (at least one per direction)."""
    extents = (bounds[1] - bounds[0], bounds[3] - bounds[2], bounds[5] - bounds[4])
    return tuple(max(1, round(e / size)) for e in extents)  # type: ignore[return-value]


def location_in_mesh(domain: Bounds, parts: Bounds, cells: tuple[int, int, int],
                     inlet_x: float | None = None) -> tuple[float, float, float]:
    """A point inside the domain, outside every part and away from background cell faces.

    ``domain`` is the background box and ``cells`` its cells. The point lies upstream of the parts'
    bounding box (so outside all parts), halfway between the inlet (``inlet_x``: where the axis meets a
    rounded domain's front; the box's x_min by default) and the parts, in the cell column that
    contains the middle of the parts' y and z range, at a fraction of the cell that is not on a face of
    any refinement level.
    """
    point = []
    front = domain[0] if inlet_x is None else inlet_x
    for axis in range(3):
        lo, hi = domain[2 * axis], domain[2 * axis + 1]
        step = (hi - lo) / cells[axis]
        if axis == 0:
            target = (front + parts[0]) / 2  # between the inlet and the parts
        else:
            target = (parts[2 * axis] + parts[2 * axis + 1]) / 2
        index = min(cells[axis] - 1, max(0, int((target - lo) / step)))
        point.append(lo + (index + LOCATION_OFFSET[axis]) * step)
    return tuple(point)  # type: ignore[return-value]


def _hex_faces(bounds: Bounds) -> dict[str, list[int]]:
    """Outward-facing vertex loops of the block's faces (vertex numbering of ``block_mesh``)."""
    return {
        "x_min": [0, 4, 7, 3], "x_max": [1, 2, 6, 5],
        "y_min": [0, 1, 5, 4], "y_max": [3, 7, 6, 2],
        "z_min": [0, 3, 2, 1], "z_max": [4, 5, 6, 7],
    }


def ground_split(x0: float, x1: float, nx: int, wall_start: float) -> int:
    """The background cell face where the ground wall starts (D-118): the index of the face nearest to
    ``wall_start``, kept between 1 and nx - 1 so both the slip strip and the wall have faces."""
    return min(nx - 1, max(1, round((wall_start - x0) / ((x1 - x0) / nx))))


def ground_split_x(inp: MeshCaseInput) -> float | None:
    """The x where the ground wall actually starts in the mesh (the nearest background cell face to
    ``ground_wall_start``), or None without a slip strip."""
    if inp.rounded or not inp.ground or inp.ground_wall_start is None:
        return None
    est = inp.estimate()
    x0, x1 = est.background_bounds[0], est.background_bounds[1]
    return x0 + ground_split(x0, x1, est.cells[0], inp.ground_wall_start) * (x1 - x0) / est.cells[0]


def block_mesh_dict(inp: MeshCaseInput) -> FoamFileSpec:
    est = inp.estimate()
    x0, x1, y0, y1, z0, z1 = est.background_bounds
    cells = est.cells
    faces = _hex_faces(est.background_bounds)
    split = ground_split_x(inp)
    if split is not None:  # two blocks sharing the face x = split (D-118): the same cells as one block
        return _split_block_mesh_dict(inp, est.background_bounds, cells, split)
    if inp.rounded or inp.internal:  # the background box of a rounded domain (D-078) or of internal flow (D-129)
        others = ["x_min", "x_max", "z_min", "z_max"] + ([] if inp.two_d else ["y_max"])
        patches = [(BACKGROUND_PATCH, others + ([] if inp.symmetric or inp.two_d else ["y_min"]))]
    else:
        patches = [
            ("inlet", ["x_min"]),
            ("outlet", ["x_max"]),
            ("top", ["z_max"]),
            (GROUND_PATCH if inp.ground else "bottom", ["z_min"]),
        ]
        if not inp.two_d:
            patches.insert(2, ("sides", ["y_max"] if inp.symmetric else ["y_min", "y_max"]))
    if inp.two_d:  # the slab's spanwise faces (D-121)
        patches += [(FRONT_PATCH, ["y_min"]), (BACK_PATCH, ["y_max"])]
    if inp.symmetric:
        patches.append(("symmetry", ["y_min"]))
    return FoamFileSpec(content={
        "scale": 1,
        "vertices": [
            [x0, y0, z0], [x1, y0, z0], [x1, y1, z0], [x0, y1, z0],
            [x0, y0, z1], [x1, y0, z1], [x1, y1, z1], [x0, y1, z1],
        ],
        "blocks": ["hex", [0, 1, 2, 3, 4, 5, 6, 7], list(cells), "simpleGrading", [1, 1, 1]],
        "edges": [],
        "boundary": [
            (name, {"type": BOUNDARY_PATCH_TYPES.get(name, "patch"), "faces": [faces[f] for f in which]})
            for name, which in patches
        ],
        "mergePatchPairs": [],
    })


def _split_block_mesh_dict(inp: MeshCaseInput, bounds: Bounds, cells, xs: float) -> FoamFileSpec:
    """The box background as two blocks split at x = ``xs`` (a background cell face): the upstream
    block's z_min face is the slip strip "ground_slip", the downstream one's the ground wall (D-118)."""
    x0, x1, y0, y1, z0, z1 = bounds
    nx, ny, nz = cells
    n_up = ground_split(x0, x1, nx, inp.ground_wall_start)
    vertices = [[x, y, z] for z in (z0, z1) for y in (y0, y1) for x in (x0, xs, x1)]

    def v(i: int, j: int, k: int) -> int:  # x index 0..2, y index 0..1, z index 0..1
        return k * 6 + j * 3 + i

    def block(i: int) -> list[int]:
        return [v(i, 0, 0), v(i + 1, 0, 0), v(i + 1, 1, 0), v(i, 1, 0),
                v(i, 0, 1), v(i + 1, 0, 1), v(i + 1, 1, 1), v(i, 1, 1)]

    def face(i: int, which: str) -> list[int]:
        b = block(i)  # the vertex loops of _hex_faces on this block's vertices
        return [b[n] for n in _hex_faces(bounds)[which]]

    patches = [
        ("inlet", [face(0, "x_min")]),
        ("outlet", [face(1, "x_max")]),
        ("sides", [face(i, "y_max") for i in (0, 1)] + ([] if inp.symmetric else [face(i, "y_min") for i in (0, 1)])),
        ("top", [face(i, "z_max") for i in (0, 1)]),
        (GROUND_SLIP_PATCH, [face(0, "z_min")]),
        (GROUND_PATCH, [face(1, "z_min")]),
    ]
    if inp.two_d:  # the slab's spanwise faces (D-121)
        patches = [p for p in patches if p[0] != "sides"] + [
            (FRONT_PATCH, [face(i, "y_min") for i in (0, 1)]), (BACK_PATCH, [face(i, "y_max") for i in (0, 1)])]
    if inp.symmetric:
        patches.append(("symmetry", [face(i, "y_min") for i in (0, 1)]))
    return FoamFileSpec(content={
        "scale": 1,
        "vertices": vertices,
        "blocks": ["hex", block(0), [n_up, ny, nz], "simpleGrading", [1, 1, 1],
                   "hex", block(1), [nx - n_up, ny, nz], "simpleGrading", [1, 1, 1]],
        "edges": [],
        "boundary": [(name, {"type": BOUNDARY_PATCH_TYPES[name], "faces": fs}) for name, fs in patches],
        "mergePatchPairs": [],
    })


def surface_feature_extract_dict(inp: MeshCaseInput) -> FoamFileSpec:
    """One extractFromSurface entry per part STL (includedAngle = 180 - feature angle)."""
    content = {}
    for name in inp.parts + ((DOMAIN_SURFACE,) if inp.rounded else ()):
        content[f"{name}.stl"] = {
            "extractionMethod": "extractFromSurface",
            "includedAngle": 180.0 - inp.mesh.feature_angle,
            "subsetFeatures": {"nonManifoldEdges": False, "openEdges": True},
            "writeObj": False,
        }
    return FoamFileSpec(content=content)


def _layer_sizing(inp: MeshCaseInput) -> dict:
    """Layer size keywords: relative to the local cell, or absolute from the y+ estimate.

    Absolute: relativeSizes false, firstLayerThickness = the estimator's value (with the
    expansion ratio this fixes the other sizes) and minThickness as a fraction of it.
    """
    m = inp.mesh
    if inp.fixed_layers is not None:
        h = inp.fixed_layers[0]
        return {"relativeSizes": False, "firstLayerThickness": h, "minThickness": m.min_thickness * h}
    if m.layer_sizing == "relative":
        return {"relativeSizes": True, "finalLayerThickness": m.final_layer_thickness,
                "minThickness": m.min_thickness}
    if inp.first_layer_thickness is None:
        raise ValueError("layer_sizing 'absolute_yplus' needs first_layer_thickness")
    h = inp.first_layer_thickness
    return {"relativeSizes": False, "firstLayerThickness": h, "minThickness": m.min_thickness * h}


