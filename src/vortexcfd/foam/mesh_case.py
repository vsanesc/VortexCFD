def prepare_case_dir(case_dir: Path, files: dict[str, FoamFileSpec]) -> None:
    """Create or refresh the meshing case directory.

    A new or empty directory gets the marker file. An existing non-empty directory must carry
    the marker (it is ours); then only ``constant/polyMesh`` is removed and the generated
    dictionaries are overwritten. Nothing else is ever deleted.

    Raises:
        CaseDirectoryNotOursError: the directory has files but no marker.
    """
    case_dir = Path(case_dir)
    marker = case_dir / MARKER_NAME
    if case_dir.exists() and any(case_dir.iterdir()) and not marker.is_file():
        raise CaseDirectoryNotOursError(
            f"'{case_dir}' is not empty and was not generated by VortexCFD "
            f"(marker file {MARKER_NAME} missing); refusing to touch it."
        )
    case_dir.mkdir(parents=True, exist_ok=True)
    marker.write_text(MARKER_TEXT, encoding="utf-8")
    poly_mesh = case_dir / "constant" / "polyMesh"
    if poly_mesh.is_dir():
        shutil.rmtree(poly_mesh)
    (case_dir / TRI_SURFACE).mkdir(parents=True, exist_ok=True)
    for rel, spec in files.items():
        target = case_dir / rel
        write_foam_file(target, spec.content, object_name=Path(rel).name, class_name=spec.class_name)
    (case_dir / "case.foam").touch()  # lets the OpenFOAM reader open the case


RUN_RECORD_FILE = "vortexcfd_run.json"  # foam/run_record.RUN_RECORD_NAME (kept in sync by a test)


def _is_result_time(name: str) -> bool:
    try:
        return float(name) > 0
    except ValueError:
        return False


def remove_results(case_dir: Path) -> list[str]:
    """Delete the solver results of a marker-protected case: time directories after 0,
    postProcessing/ and the run record. Returns the removed names (sorted). Nothing else is touched
    (0/, constant/, system/, logs and the meshing dictionaries stay).

    Raises:
        CaseDirectoryNotOursError: the directory has no VortexCFD marker.
    """
    case_dir = Path(case_dir)
    if not (case_dir / MARKER_NAME).is_file():
        raise CaseDirectoryNotOursError(
            f"'{case_dir}' was not generated by VortexCFD (marker file {MARKER_NAME} missing); "
            "refusing to delete results in it."
        )
    removed = []
    for child in sorted(case_dir.iterdir(), key=lambda c: c.name):
        if child.is_dir() and not child.is_symlink() and (_is_result_time(child.name) or child.name == "postProcessing"):
            shutil.rmtree(child)
            removed.append(child.name)
    record = case_dir / RUN_RECORD_FILE
    if record.is_file():
        record.unlink()
        removed.append(RUN_RECORD_FILE)
    return removed
