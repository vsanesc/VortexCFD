@dataclass(frozen=True)
class MeshCaseInput:
    """Everything the meshing dictionaries depend on (plain data, metres)."""

    domain_bounds: Bounds
    symmetric: bool  # a symmetry plane at y_min
    parts: tuple[str, ...]  # safe, unique patch names (see ``safe_part_names``)
    parts_bounds: Bounds  # union of the parts' bounding boxes
    reference_length: float  # L, the largest extent of the parts (domain sizes)
    mesh: Mesh
    # First prism-layer thickness (m) for layer_sizing "absolute_yplus" (see foam/yplus.py).
    first_layer_thickness: float | None = None
    # Number of layers for layer_sizing "absolute_yplus" (foam/yplus.plan_layers); mesh.layers is
    # used for relative sizing only.
    layer_count: int | None = None
    # The expansion ratio written for an absolute stack (first_layer_thickness / fixed_layers): the layer
    # plan's, which the layer cap may raise above mesh.expansion_ratio (D-106). None: mesh.expansion_ratio.
    layer_expansion: float | None = None
    # Per part, in the order of ``parts``: its bounding box (metres) and its (surface_level_min,
    # surface_level_max) overrides (None = the mesh's levels). Empty: no per-part data.
    part_bounds: tuple[Bounds, ...] = ()
    part_levels: tuple[tuple[int | None, int | None], ...] = ()
    # (first layer thickness in metres, number of layers): an absolute layer stack that replaces
    # both sizings (mesh study levels share one stack, D-066); the quality controls still follow
    # mesh.layer_sizing. None: the sizing above.
    fixed_layers: tuple[float, int] | None = None
    # Per part, in the order of ``parts``: its wall patches (safe names, part_patch_names). Empty, or
    # a part whose only patch is its own name: the part's surface is one patch, as before regions.
    # Otherwise the part's STL holds one solid per patch and each becomes a snappyHexMesh region
    # with its own wall patch (D-071).
    part_patches: tuple[tuple[str, ...], ...] = ()
    # The domain shape ("box", "bullet", "c_type"); a rounded shape needs its exact volume, the
    # patches of its surface (the solids of domain.stl, in order) and the inlet's x on the axis (for
    # locationInMesh). The box keeps the blockMesh faces as its patches.
    domain_shape: str = "box"
    domain_volume: float | None = None
    domain_patches: tuple[str, ...] = ()
    inlet_x: float | None = None
    # The length target_surface_size multiplies (l_ref or L, Mesh.surface_size_reference, resolved by
    # the caller; D-085). None: reference_length.
    surface_length: float | None = None
    # Extra feature edge files in constant/triSurface with their refinement level: the intersection
    # curves of the surface preparation (D-093), snapped to like every feature.
    extra_features: tuple[tuple[str, int], ...] = ()
    # The user refinement volumes to write (D-103): enabled and not wholly outside the domain (the
    # workflow decides), each with its refinement level.
    volumes: tuple["VolumeEntry", ...] = ()
    # The ground plane (box domains, D-116): the z_min face is the wall patch "ground" instead of the far
    # field "bottom"; ``ground_layers`` gives it the parts' prism layers. [NUMERICS-REVIEW]
    ground: bool = False
    ground_layers: bool = False
    # x where the ground wall starts (D-118): the z_min face ahead of it is the slip patch
    # "ground_slip". The background mesh is split there into two blocks at the nearest background cell
    # face (ground_split), so its cells are unchanged. None: the whole face is the ground. [NUMERICS-REVIEW]
    ground_wall_start: float | None = None
    # The 2D mode (D-121): a section in x-z meshed in a slab one cell across the span (y), the parts' surface
    # levels and the refinement volumes applied as directional (x and z) refinement, then extruded into one
    # cell with the empty patch "frontAndBack". [NUMERICS-REVIEW]
    two_d: bool = False
    # A mesh study level (D-127): the current settings' cell size over this level's (1 / its factor; 1 for the
    # current level and every single mesh). Other than 1, a 2D section's staircase boxes keep the current level's
    # extent in metres (section_staircases), so a finer level is finer everywhere.
    buffer_scale: float = 1.0
    # snappyHexMesh's nCellsBetweenLevels in 3D (D-127): CELLS_BETWEEN_LEVELS for every single mesh and a study's
    # current level, study_cells_between_levels for the other levels of a 3D study. 2D always uses
    # CELLS_BETWEEN_LEVELS (its transitions are the staircases).
    cells_between_levels: int = CELLS_BETWEEN_LEVELS
    # Internal flow (D-129) [NUMERICS-REVIEW]: no domain; the background box encloses the parts (domain_bounds are
    # their bounds, domain_volume the fluid volume) with BACKGROUND_MARGIN_CELLS base cells on every side, its faces
    # the patch "background", which the fluid inside the parts never touches (createPatch removes it; the domain
    # guard checks it is empty). ``open_patches``: the inlet and outlet patches (safe names) with their role; every
    # other part patch is a wall, the only patches with prism layers. ``location``: the locationInMesh found inside
    # the closed geometry (workflow/internal.py).
    internal: bool = False
    open_patches: tuple[tuple[str, str], ...] = ()
    location: tuple[float, float, float] | None = None

    @property
    def rounded(self) -> bool:
        return self.domain_shape != "box"

    def estimate(self, mesh: Mesh | None = None):
        """The mesh estimate of this domain (mesh_estimate.estimate_mesh)."""
        length = self.surface_length if self.surface_length is not None else self.reference_length
        return estimate_mesh(self.domain_bounds, length, mesh or self.mesh, volume=self.domain_volume,
                             rounded=self.rounded, symmetric=self.symmetric, two_d=self.two_d, internal=self.internal)

    def expected_domain_patches(self) -> tuple[str, ...]:
        """The domain patches the final mesh must have (each with faces). In 2D the spanwise ones are the empty
        "frontAndBack" (the box's sides and the C-type's spanwise sides lie outside the slab)."""
        if self.internal:  # the inlets and outlets (D-129)
            return tuple(p for p, _role in self.open_patches) + ((FRONT_AND_BACK,) if self.two_d else ())
        if not self.rounded:
            names = ["inlet", "outlet", "sides", "top", GROUND_PATCH if self.ground else "bottom"]
            if self.ground and self.ground_wall_start is not None:
                names.append(GROUND_SLIP_PATCH)
        else:
            names = list(self.domain_patches)
        if self.two_d:
            names = [n for n in names if n != "sides"] + [FRONT_AND_BACK]
        return tuple(names + (["symmetry"] if self.symmetric else []))

    def patches_of(self, index: int) -> tuple[str, ...]:
        if index < len(self.part_patches) and self.part_patches[index]:
            return self.part_patches[index]
        return (self.parts[index],)

    def has_regions(self, index: int) -> bool:
        return self.patches_of(index) != (self.parts[index],)

    @property
    def patches(self) -> tuple[str, ...]:
        """Every part wall patch of the mesh (the lost-part guard checks each one)."""
        return tuple(p for i in range(len(self.parts)) for p in self.patches_of(i))

    def patch_type(self, patch: str) -> str:
        """The OpenFOAM type of a part patch: "patch" for an internal-flow inlet or outlet (D-129), else "wall"."""
        return "patch" if patch in dict(self.open_patches) else "wall"


