# The meshing steps, run in order from the case directory (each through FoamRun).
MESH_COMMANDS: tuple[tuple[str, list[str]], ...] = (
    ("blockMesh", ["blockMesh"]),
    ("surfaceFeatureExtract", ["surfaceFeatureExtract"]),
    ("snappyHexMesh.castellate", ["snappyHexMesh", "-overwrite", "-dict", CASTELLATE_DICT]),  # seeded parts only
    ("snappyHexMesh", ["snappyHexMesh", "-overwrite"]),
    ("extrudeMesh", ["extrudeMesh"]),  # 2D only (system/extrudeMeshDict, D-121)
    ("createPatch", ["createPatch", "-overwrite"]),  # rounded domains, 2D and internal flow (system/createPatchDict)
    ("checkMesh", ["checkMesh"]),
)


# Parallel meshing (D-111) [NUMERICS-REVIEW]: blockMesh and surfaceFeatureExtract stay serial, decomposePar
# splits the background mesh once (system/decomposeParDict, scotch: written by MeshRun), every
# snappyHexMesh pass runs on the decomposed case through mpirun with -parallel (snappyHexMesh rebalances
# with the same method, its own maxLoadUnbalance), and reconstructParMesh -constant (with -overwrite the
# passes write the mesh to processor*/constant, as in the v2606 motorBike tutorial) merges it once into
# constant/polyMesh; createPatch and checkMesh then run on that serial mesh.
DECOMPOSE_STEP = "decomposePar"
# The meshing decomposition splits the mesh only (D-130): a case that was solved before has 0/ fields, and their
# patches are those of the previous mesh (no "background" patch of a rounded domain or of internal flow, D-078,
# D-129), which decomposePar -force would read and fail on.
MESH_DECOMPOSE_COMMAND = [*DECOMPOSE_COMMAND, "-no-fields"]
RECONSTRUCT_STEP = "reconstructParMesh"
SNAPPY_STEPS = ("snappyHexMesh.castellate", "snappyHexMesh")


def mesh_commands(cores: int = 1) -> tuple[tuple[str, list[str]], ...]:
    """The meshing steps on ``cores`` ranks: MESH_COMMANDS unchanged for 1 (serial)."""
    if cores <= 1:
        return MESH_COMMANDS
    steps: list[tuple[str, list[str]]] = []
    for name, command in MESH_COMMANDS:
        if name in SNAPPY_STEPS:
            if not any(step == DECOMPOSE_STEP for step, _ in steps):
                steps.append((DECOMPOSE_STEP, list(MESH_DECOMPOSE_COMMAND)))
            steps.append((name, parallel_command(command, cores)))
            if name == "snappyHexMesh":
                steps.append((RECONSTRUCT_STEP, ["reconstructParMesh", "-constant"]))
        else:
            steps.append((name, command))
    return tuple(steps)


# Generated dictionaries that only some set-ups have (a run skips a step whose dictionary is missing).
OPTIONAL_DICTS = ("system/surfaceFeatureExtractDict", "system/createPatchDict", CASTELLATE_DICT, EXTRUDE_DICT)
# The step that runs only when its dictionary was written.
STEP_DICTS = {"surfaceFeatureExtract": "system/surfaceFeatureExtractDict", "createPatch": "system/createPatchDict",
              "snappyHexMesh.castellate": CASTELLATE_DICT, "extrudeMesh": EXTRUDE_DICT}


def prepare_case_dir(case_dir: Path, files: dict[str, FoamFileSpec]) -> None:
    """Create or refresh the meshing case directory.

    A new or empty directory gets the marker file. An existing non-empty directory must carry
    the marker (it is ours); then only ``constant/polyMesh`` and the mesh record (it described that
    mesh: a stopped or failed run leaves the mesh not generated, D-111) are removed and the generated
    dictionaries are overwritten. Nothing else is ever deleted.

    Raises:
        CaseDirectoryNotOursError: the directory has files but no marker.
    """
    case_dir = Path(case_dir)
    marker = case_dir / MARKER_NAME
    if case_dir.exists() and any(case_dir.iterdir()) and not marker.is_file():
        raise CaseDirectoryNotOursError(
            f"'{case_dir}' is not empty and was not generated by VortexCFD "
            f"(marker file {MARKER_NAME} missing); refusing to touch it."
        )
    case_dir.mkdir(parents=True, exist_ok=True)
    marker.write_text(MARKER_TEXT, encoding="utf-8")
    poly_mesh = case_dir / "constant" / "polyMesh"
    if poly_mesh.is_dir():
        shutil.rmtree(poly_mesh)
    (case_dir / MESH_RECORD_FILE).unlink(missing_ok=True)
    (case_dir / TRI_SURFACE).mkdir(parents=True, exist_ok=True)
    for rel in OPTIONAL_DICTS:  # a dictionary of an earlier set-up that this one does not use
        if rel not in files:
            (case_dir / rel).unlink(missing_ok=True)
    for rel, spec in files.items():
        target = case_dir / rel
        write_foam_file(target, spec.content, object_name=Path(rel).name, class_name=spec.class_name)
    (case_dir / "case.foam").touch()  # lets the OpenFOAM reader open the case


RUN_RECORD_FILE = "vortexcfd_run.json"  # foam/run_record.RUN_RECORD_NAME (kept in sync by a test)
MESH_RECORD_FILE = "vortexcfd_mesh.json"  # foam/mesh_record.RECORD_NAME (kept in sync by a test)


def _is_result_time(name: str) -> bool:
    try:
        return float(name) > 0
    except ValueError:
        return False


_PROCESSOR_RE = re.compile(r"^processor\d+$")


def clear_mesh(case_dir: Path) -> list[str]:
    """Delete the generated mesh of a marker-protected case: the solver results (``remove_results``), then
    constant/polyMesh and the mesh record. The dictionaries, 0/, the surfaces and the logs stay. Returns the removed
    names.

    Raises:
        CaseDirectoryNotOursError: the directory has no VortexCFD marker.
    """
    case_dir = Path(case_dir)
    if not case_dir.is_dir():
        return []
    removed = remove_results(case_dir)
    poly_mesh = case_dir / "constant" / "polyMesh"
    if poly_mesh.is_dir():
        shutil.rmtree(poly_mesh)
        removed.append("constant/polyMesh")
    record = case_dir / MESH_RECORD_FILE
    if record.is_file():
        record.unlink()
        removed.append(MESH_RECORD_FILE)
    return removed


def remove_results(case_dir: Path) -> list[str]:
    """Delete the solver results of a marker-protected case: time directories after 0,
    postProcessing/, the processor* directories of a parallel run (they also hold a decomposed
    copy of the mesh, D-063) and the run record. Returns the removed names (sorted). Nothing else is touched
    (0/, constant/, system/, logs and the meshing dictionaries stay).

    Raises:
        CaseDirectoryNotOursError: the directory has no VortexCFD marker.
    """
    case_dir = Path(case_dir)
    if not (case_dir / MARKER_NAME).is_file():
        raise CaseDirectoryNotOursError(
            f"'{case_dir}' was not generated by VortexCFD (marker file {MARKER_NAME} missing); "
            "refusing to delete results in it."
        )
    removed = []
    for child in sorted(case_dir.iterdir(), key=lambda c: c.name):
        if child.is_dir() and not child.is_symlink() and (
            _is_result_time(child.name) or child.name == "postProcessing" or _PROCESSOR_RE.match(child.name)
        ):
            shutil.rmtree(child)
            removed.append(child.name)
    record = case_dir / RUN_RECORD_FILE
    if record.is_file():
        record.unlink()
        removed.append(RUN_RECORD_FILE)
    return removed
