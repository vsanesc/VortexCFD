"""Turbulent smooth-pipe validation case (task w3-internal, Part B; docs/validation/pipe/SETUP.md): a straight pipe
generated by code, set up through the app's "Internal flow" preset, a mass-flow inlet and a static outlet.

Fluid: water-like round values (rho 1000 kg/m3, nu 1.0e-6 m2/s; water at about 20 degC: 998.2 kg/m3, 1.004e-6
m2/s). D = 0.1 m, bulk velocity 1.0 m/s: Re_D = 1.0e5. Length 80 D: the friction factor is taken between 50 D and
70 D, and the segments 50-60 D and 60-70 D must agree (developed flow).
"""

import math
from pathlib import Path

from vortexcfd.bench.internal_geometries import write_pipe
from vortexcfd.core.model import AsymptoticCriterion, Simulation, StoppingCriteria
from vortexcfd.core.presets import BUILTIN_PRESETS, apply_preset
from vortexcfd.core.project import Project
from vortexcfd.geometry.loader import stl_solid_names
from vortexcfd.workflow import part_ops

D = 0.1  # m
LENGTH_D = 80  # pipe length in diameters
RHO = 1000.0  # kg/m3
NU = 1.0e-6  # m2/s
REYNOLDS = 1.0e5
U_BULK = REYNOLDS * NU / D  # 1.0 m/s
AREA = math.pi * D ** 2 / 4
MASS_FLOW = RHO * U_BULK * AREA  # 7.853982 kg/s
N_THETA = 64  # surface points around the circumference
AXIAL_TRIANGLE = 0.05  # m: the straight wall's triangles along x (the surface is exact along x)
# Measurement planes (x in diameters): the friction factor over 50-70 D; 40-50, 50-60 and 60-70 D show the development.
PLANES_D = (40, 50, 60, 70)
DROPS = {"dp_40_50": (40, 50), "dp_50_60": (50, 60), "dp_60_70": (60, 70), "dp_50_70": (50, 70)}
MAIN_DROP = "dp_50_70"
ITERATIONS = 4000
CORES = 10


def prandtl_karman(re: float) -> float:
    """Darcy friction factor of a smooth pipe: 1 / sqrt(f) = 2.0 log10(Re sqrt(f)) - 0.8 (Prandtl-Karman, e.g.
    Schlichting, Boundary-Layer Theory), solved by fixed-point iteration."""
    f = 0.02
    for _ in range(100):
        f = (2.0 * math.log10(re * math.sqrt(f)) - 0.8) ** -2
    return f


def colebrook_smooth(re: float) -> float:
    """Colebrook-White with zero roughness: 1 / sqrt(f) = -2.0 log10(2.51 / (Re sqrt(f)))."""
    f = 0.02
    for _ in range(100):
        f = (-2.0 * math.log10(2.51 / (re * math.sqrt(f)))) ** -2
    return f


def friction_factor(dp: float, length: float, rho: float = RHO, u: float = U_BULK, d: float = D) -> float:
    """Darcy f = (dp / L) D / (0.5 rho U^2)."""
    return dp / length * d / (0.5 * rho * u ** 2)


def stopping() -> StoppingCriteria:
    """The main pressure drop and the outlet mass flow settled over 200 iterations (relative range 1e-3 and 1e-4),
    after at least 500 iterations; the iteration limit is ITERATIONS. [NUMERICS-REVIEW: the validation's choice]"""
    return StoppingCriteria(criteria=[
        AsymptoticCriterion(quantity=f"dp:{MAIN_DROP}:static", window=200, tolerance=1e-3, floor=1.0),
        AsymptoticCriterion(quantity="flow:mdot:patch:outlet", window=200, tolerance=1e-4, floor=0.01),
    ], combine="all", min_iterations=500)


def build_project(folder: Path, inlet: dict | None = None) -> Project:
    """The pipe project in ``folder``/pipe (created): the preset, the geometry with one patch per solid, the roles,
    the fluid, the planes and pressure drops and the solver settings. ``inlet``: the inlet settings (default: the
    mass flow MASS_FLOW)."""
    folder.mkdir(parents=True, exist_ok=True)
    preset = next(p for p in BUILTIN_PRESETS if p.name == "Internal flow")
    project = Project.create(folder, "pipe", apply_preset(Simulation(name="pipe"), preset))
    stl = write_pipe(project.folder / "geometry" / "pipe.stl", D, LENGTH_D * D, N_THETA, AXIAL_TRIANGLE)
    project.add_part(part_ops.with_region_patches(
        part_ops.part_with_solid_regions(project.folder, "pipe", stl, "m", stl_solid_names(stl))))
    project.update_physics(nu=NU, rho_ref=RHO)
    project.update_boundary("inlet", role="inlet", inlet=inlet or {"kind": "mass_flow", "mass_flow": MASS_FLOW})
    project.update_boundary("outlet", role="outlet", outlet={"pressure": 0.0})
    planes = [{"name": f"x{n}D", "point": (n * D, 0.0, 0.0), "normal": (1.0, 0.0, 0.0)} for n in PLANES_D]
    drops = [{"name": name, "upstream": f"plane:x{a}D", "downstream": f"plane:x{b}D"} for name, (a, b) in DROPS.items()]
    project.update_reports(planes=planes, pressure_drops=drops,
                           slots=[f"dp:{MAIN_DROP}:static", "flow:mdot:patch:outlet", "mass_imbalance"])
    project.update_solver(iterations=ITERATIONS, write_interval=ITERATIONS, cores=CORES, stopping=stopping())
    project.update_study("mesh", quantities=[f"dp:{MAIN_DROP}:static"])
    project.save()
    return project
