"""The Ahmed body (25 degree slant) in ground proximity, set up through the app's own pipeline (task
validation-ahmed; docs/validation/ahmed/SETUP.md lists every input with its source).

Geometry (generated by code, deterministic; the STEP files go to the git-ignored project folder):
- the half body: the benchmark's Ahmed body (bench/geometries.py: length 1044 mm, width 389 mm, height
  288 mm, front edges rounded R100, 25 degree slant 222 mm long; Ahmed et al. 1984, Fig. 1) cut at its
  plane of symmetry, kept for y >= 0 and raised by the 50 mm ground clearance (Ahmed et al. 1984,
  section 2: "fixed on cylindrical stilts 50 mm above a ground board");
- two stilts (the half model's two of the four), cylinders of 30 mm diameter (ERCOFTAC KBwiki AC1-05:
  "placed on stilts of 30 mm diameter"; Ahmed et al. 1984 does not dimension them), centred 202 mm and
  672 mm behind the nose (Fig. 1: 202 and 470 mm) and 163.5 mm from the plane of symmetry (Fig. 1),
  from STILT_BELOW below the ground plane to STILT_INSIDE inside the body, so the domain and the body
  both cut them cleanly (owner decision V2).

Axes: x along the flow from the nose (x = 0), y spanwise from the plane of symmetry, z up from the ground
plane (z = 0).
"""

import math
import shutil
from pathlib import Path

from vortexcfd.bench import geometries as bench_geo
from vortexcfd.core.model import (
    AsymptoticCriterion,
    Ground,
    ResidualCriterion,
    Simulation,
    StoppingCriteria,
)
from vortexcfd.core.presets import BUILTIN_PRESETS, apply_preset
from vortexcfd.core.project import Project
from vortexcfd.workflow import part_ops

# -- reference data (docs/validation/ahmed/SETUP.md) ------------------------------------------------------
LENGTH = 1.044  # m, Ahmed et al. 1984, Fig. 1 and nomenclature
WIDTH = 0.389  # m
HEIGHT = 0.288  # m
CLEARANCE = 0.050  # m, ground clearance
SPEED = 60.0  # m/s, Ahmed et al. 1984 ("All tests ... at a wind speed of 60 m/s")
REYNOLDS = 4.29e6  # on the model length, Ahmed et al. 1984
NU = SPEED * LENGTH / REYNOLDS  # 1.4601e-5 m2/s: the air of the experiment through its Reynolds number
TURBULENCE_INTENSITY = 0.005  # "the turbulence intensity lies below 0.5 per cent" (upper bound used)
FRONTAL_AREA = WIDTH * HEIGHT  # 0.112032 m2, "projected frontal area of model" (the body, no stilts)
A_REF_HALF = FRONTAL_AREA / 2  # the half model's forces are half the body's
UPSTREAM_BOARD = 1.35  # L: "About 1.35 model length of ground plane projected in front"
STILT_DIAMETER = 0.030  # m, ERCOFTAC AC1-05
STILT_X = (0.202, 0.672)  # m from the nose, Ahmed et al. 1984 Fig. 1 (202, 202 + 470)
STILT_Y = 0.1635  # m from the plane of symmetry, Fig. 1
STILT_BELOW = 0.010  # m below the ground plane (cut by the domain)
STILT_INSIDE = 0.010  # m inside the body (cut by the body)
# CAD tessellation: finer than the import defaults (1/1000 of the diagonal, 20 degrees), which leave the
# R100 nose fillets with 1.5 mm chord error and 4 or 5 facets per quarter circle.
LINEAR_DEFLECTION = 1e-4  # m
ANGULAR_DEFLECTION = 5.0  # degrees: chord error 0.1 mm on R100, 0.014 mm on the stilts

# The experimental value compared against and the published k-omega SST results (RESULT.md, references).
CD_EXPERIMENT = 0.285  # Ahmed et al. 1984 Fig. 4, 25 degrees, stilt tare removed (as quoted, see SETUP.md)
CD_EXPERIMENT_ALT = 0.2875  # the same figure as read by SimScale (SETUP.md)
# Published k-omega SST Cd of the 25 degree body (RESULT.md, references): Hachimy et al. 2022, SimScale, SimFlow.
PUBLISHED_SST_CD = (0.2839, 0.2915, 0.313)
PASS_LIMIT, NOTE_LIMIT = 0.10, 0.20  # V6


def consistent_with_sst(cd: float) -> bool:
    """V6's condition for PASS WITH NOTE: the value lies within the range of the published k-omega SST
    results (no widening: the study gives the fine value no grid uncertainty, RESULT.md)."""
    return min(PUBLISHED_SST_CD) <= cd <= max(PUBLISHED_SST_CD)


def verdict(error: float, consistent: bool) -> str:
    """The V6 band of a relative error: PASS within 10 %; PASS WITH NOTE within 10-20 % when consistent
    with the published k-omega SST results; FAIL otherwise (above 20 %, or 10-20 % and not consistent)."""
    if abs(error) <= PASS_LIMIT:
        return "PASS"
    if abs(error) <= NOTE_LIMIT and consistent:
        return "PASS WITH NOTE"
    return "FAIL"


def judged_value(values: list[float], sizes: list[float]):
    """(value, basis, GCI result) of three levels, coarse first: the extrapolated value when the GCI applies
    and is in the asymptotic range, else the finest grid's (V6)."""
    from vortexcfd.foam import gci

    result = gci.study(values, sizes)
    if result.applicable and result.in_asymptotic_range:
        return result.extrapolated, "extrapolated", result
    return values[-1], "fine", result

# -- app set-up ----------------------------------------------------------------------------------------
PROJECT_NAME = "ahmed25"
BODY, STILT_FRONT, STILT_REAR = "body", "stilt_front", "stilt_rear"
DOMAIN = {"upstream": UPSTREAM_BOARD, "downstream": 10.0, "lateral": 5.0, "vertical": 5.0, "symmetry": "y_min",
          "ground": Ground(enabled=True, motion="stationary", position="value", z=0.0).model_dump()}
SOLVER_CORES = 4  # foam/parallel.recommended_cores on this machine (D-064)
ITERATIONS = 1500  # iteration limit
AVERAGE_WINDOW = 1000  # iterations averaged for the judged values (the oscillation period is about 170)
# The fine level's sizing targets (the mesh study's "current" settings): twice finer in linear size than
# the app defaults (background 100,000 cells, surface 0.01 l_ref), which give 216,549 cells here.
BACKGROUND_CELLS = 800_000
SURFACE_SIZE = 0.005
STUDY_RATIO = math.sqrt(2.0)  # the mesh study's default ratio in linear cell size (D-066)
STUDY_QUANTITIES = ["Cd@body", "Cd", "Cl@body", "Cl", "Cd_pressure@body", "Cd_viscous@body", "Cd@stilt_front",
                    "Cd@stilt_rear", "Cl_pressure@body", "Cl_viscous@body"]


def _half_body_shape():
    from OCP.BRepAlgoAPI import BRepAlgoAPI_Common
    from OCP.BRepBuilderAPI import BRepBuilderAPI_Transform
    from OCP.BRepPrimAPI import BRepPrimAPI_MakeBox
    from OCP.gp import gp_Pnt, gp_Trsf, gp_Vec

    full = bench_geo._ahmed_shape()  # millimetres, y from -194.5 to 194.5, z from 0 to 288
    keep = BRepPrimAPI_MakeBox(gp_Pnt(-10.0, 0.0, -10.0), gp_Pnt(2000.0, 500.0, 500.0)).Shape()
    common = BRepAlgoAPI_Common(full, keep)
    common.Build()
    if not common.IsDone():
        raise RuntimeError("cutting the body at its plane of symmetry failed")
    move = gp_Trsf()
    move.SetTranslation(gp_Vec(0.0, 0.0, CLEARANCE * 1000))
    return BRepBuilderAPI_Transform(common.Shape(), move, True).Shape()


def _stilt_shape(x: float):
    from OCP.BRepPrimAPI import BRepPrimAPI_MakeCylinder
    from OCP.gp import gp_Ax2, gp_Dir, gp_Pnt

    axis = gp_Ax2(gp_Pnt(x * 1000, STILT_Y * 1000, -STILT_BELOW * 1000), gp_Dir(0.0, 0.0, 1.0))
    height = (STILT_BELOW + CLEARANCE + STILT_INSIDE) * 1000
    return BRepPrimAPI_MakeCylinder(axis, STILT_DIAMETER * 500, height).Shape()


def write_geometry(folder: Path) -> dict[str, Path]:
    """The three STEP files (millimetres) in ``folder``: name -> path."""
    folder.mkdir(parents=True, exist_ok=True)
    shapes = {BODY: _half_body_shape(), STILT_FRONT: _stilt_shape(STILT_X[0]), STILT_REAR: _stilt_shape(STILT_X[1])}
    return {name: bench_geo._write_step(shape, folder / f"{name}.step") for name, shape in shapes.items()}


def stopping() -> StoppingCriteria:
    """The app's default stopping criteria for this case: its four residual criteria (p 1e-4; U, k, omega
    1e-5) and the asymptotic criterion on the body's Cd with its defaults (window 50, tolerance 1e-3),
    combined with "all". The steady solution of this case oscillates about a stationary mean (trial run,
    SETUP.md), so they are not expected to be met: the run ends at ITERATIONS and the study's values are
    the means over the last AVERAGE_WINDOW iterations (RESULT.md)."""
    residuals = [ResidualCriterion(field=f, threshold=t) for f, t in (("p", 1e-4), ("U", 1e-5), ("k", 1e-5),
                                                                       ("omega", 1e-5))]
    return StoppingCriteria(criteria=[*residuals, AsymptoticCriterion(quantity="Cd@body")], combine="all")


def build_project(work_root: Path, geometry_dir: Path) -> Project:
    """A fresh project <work_root>/ahmed25/ made as the New simulation dialog does (preset "External
    flow"), the three parts imported as File > Import Geometry does, and the validation inputs set."""
    from vortexcfd.bench.runner import import_geometry

    folder = work_root / PROJECT_NAME
    if folder.exists():
        if not (folder / f"{PROJECT_NAME}.vcfd").is_file():
            raise RuntimeError(f"{folder} exists and is not the validation project: not touching it")
        shutil.rmtree(folder)
    sim = apply_preset(Simulation(name=PROJECT_NAME), BUILTIN_PRESETS[0])
    project = Project.create(work_root, PROJECT_NAME, sim)
    for name, path in write_geometry(geometry_dir).items():
        import_geometry(project, path, "mm", mode="parts")
    for index in range(len(project.sim.geometry.parts)):  # the deflection rows of the part properties
        project.update_part(index, **part_ops.retessellate(project, index, LINEAR_DEFLECTION, ANGULAR_DEFLECTION))
    project.update_domain(**DOMAIN)
    project.update_physics(nu=NU)
    project.update_inflow(speed=SPEED, turbulence_intensity=TURBULENCE_INTENSITY)
    project.update_reports(reference_area_basis="custom", reference_area=A_REF_HALF, reference_length=LENGTH)
    project.update_solver(cores=SOLVER_CORES, iterations=ITERATIONS, write_interval=ITERATIONS,
                          stopping=stopping())
    project.save()
    return project
