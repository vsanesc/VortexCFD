def measured_rates(study_dir: Path, cores: int) -> dict[str, tuple[int, float]]:
    """Level name -> (cells, solver seconds per cell-iteration) of the levels of one round already solved on
    ``cores`` ranks, from the per-level records ``study_<level>.json`` the driver keeps in the round's
    case_study/ (a level that crashed or has no cells, iterations or time is left out)."""
    import json

    out = {}
    for name in LEVELS:
        try:
            data = json.loads((Path(study_dir) / f"study_{name}.json").read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        if data.get("cores") != cores:
            continue
        for lv in data.get("levels", []):
            if lv.get("name") != name or lv.get("state") in (None, "crashed"):
                continue
            cells, iterations, seconds = lv.get("cells"), lv.get("iterations"), lv.get("duration_s")
            if cells and iterations and seconds:
                out[name] = (int(cells), seconds / (cells * iterations))
    return out


def solver_rate(name: str, cells: int, measured: dict[str, tuple[int, float]] | None = None) -> tuple[float, str]:
    """(solver seconds per cell-iteration, its source) for a level of ``cells`` cells: the same level of the
    round if measured, else the measured level nearest in cells (the rate grows with the cells), else
    round 1's same level on SOLVER_CORES cores."""
    if measured:
        source = name if name in measured else min(measured, key=lambda n: abs(math.log(measured[n][0] / cells)))
        return measured[source][1], f"measured, {source} of this round"
    cells1, _, solve1 = ROUND1_LEVELS[name]
    return solve1 / (cells1 * ITERATIONS), f"round 1's {name} on {SOLVER_CORES} cores"


def estimate_level(name: str, cells: int, iterations: int,
                   measured: dict[str, tuple[int, float]] | None = None) -> tuple[float, float, str]:
    """(meshing seconds, solver seconds, the solver rate's source) of a level of ``cells`` cells run for
    ``iterations``: meshing from round 1's same level scaled by the cells, at least round 1's time plus 50 %
    (the ground layers and the longer domain); the solver at ``solver_rate``."""
    cells1, mesh1, _ = ROUND1_LEVELS[name]
    rate, source = solver_rate(name, cells, measured)
    return 1.5 * mesh1 * max(1.0, cells / cells1), rate * cells * iterations, source


def _half_body_shape():
    from OCP.BRepAlgoAPI import BRepAlgoAPI_Common
    from OCP.BRepBuilderAPI import BRepBuilderAPI_Transform
    from OCP.BRepPrimAPI import BRepPrimAPI_MakeBox
    from OCP.gp import gp_Pnt, gp_Trsf, gp_Vec

    full = bench_geo._ahmed_shape()  # millimetres, y from -194.5 to 194.5, z from 0 to 288
    keep = BRepPrimAPI_MakeBox(gp_Pnt(-10.0, 0.0, -10.0), gp_Pnt(2000.0, 500.0, 500.0)).Shape()
    common = BRepAlgoAPI_Common(full, keep)
    common.Build()
    if not common.IsDone():
        raise RuntimeError("cutting the body at its plane of symmetry failed")
    move = gp_Trsf()
    move.SetTranslation(gp_Vec(0.0, 0.0, CLEARANCE * 1000))
    return BRepBuilderAPI_Transform(common.Shape(), move, True).Shape()


def _stilt_shape(x: float):
    from OCP.BRepPrimAPI import BRepPrimAPI_MakeCylinder
    from OCP.gp import gp_Ax2, gp_Dir, gp_Pnt

    axis = gp_Ax2(gp_Pnt(x * 1000, STILT_Y * 1000, -STILT_BELOW * 1000), gp_Dir(0.0, 0.0, 1.0))
    height = (STILT_BELOW + CLEARANCE + STILT_INSIDE) * 1000
    return BRepPrimAPI_MakeCylinder(axis, STILT_DIAMETER * 500, height).Shape()


def write_geometry(folder: Path) -> dict[str, Path]:
    """The three STEP files (millimetres) in ``folder``: name -> path."""
    folder.mkdir(parents=True, exist_ok=True)
    shapes = {BODY: _half_body_shape(), STILT_FRONT: _stilt_shape(STILT_X[0]), STILT_REAR: _stilt_shape(STILT_X[1])}
    return {name: bench_geo._write_step(shape, folder / f"{name}.step") for name, shape in shapes.items()}


def stopping() -> StoppingCriteria:
    """The app's default stopping criteria for this case: its four residual criteria (p 1e-4; U, k, omega
    1e-5) and the asymptotic criterion on the body's Cd with its defaults (window 50, tolerance 1e-3),
    combined with "all". The steady solution of this case oscillates about a stationary mean (trial run,
    SETUP.md), so they are not expected to be met: the run ends at ITERATIONS and the study's values are
    the means over the last AVERAGE_WINDOW iterations (RESULT.md)."""
    residuals = [ResidualCriterion(field=f, threshold=t) for f, t in (("p", 1e-4), ("U", 1e-5), ("k", 1e-5),
                                                                       ("omega", 1e-5))]
    return StoppingCriteria(criteria=[*residuals, AsymptoticCriterion(quantity="Cd@body")], combine="all")


def stopping_round2() -> StoppingCriteria:
    """Round 2: the mean-stable criterion on the body's Cd with its defaults (window 500, tolerance 0.5 %,
    D-118) alone; the iteration limit ITERATIONS stays as the safety cap."""
    return StoppingCriteria(criteria=[MeanStableCriterion(quantity="Cd@body")], combine="all")


def project_name(round_: int) -> str:
    return {1: PROJECT_NAME, 2: PROJECT_NAME_R2, 3: PROJECT_NAME_R3}[round_]


def build_project(work_root: Path, geometry_dir: Path, round_: int = 1) -> Project:
    """A fresh project <work_root>/ahmed25/ (round 2: ahmed25_r2/, round 3: ahmed25_r2_nolayers/) made as the New simulation dialog does
    (preset "External flow"), the three parts imported as File > Import Geometry does, and the validation
    inputs set."""
    from vortexcfd.bench.runner import import_geometry

    name = project_name(round_)
    folder = work_root / name
    if folder.exists():
        if not (folder / f"{name}.vcfd").is_file():
            raise RuntimeError(f"{folder} exists and is not the validation project: not touching it")
        shutil.rmtree(folder)
    sim = apply_preset(Simulation(name=name), BUILTIN_PRESETS[0])
    project = Project.create(work_root, name, sim)
    for name, path in write_geometry(geometry_dir).items():
        import_geometry(project, path, "mm", mode="parts")
    for index in range(len(project.sim.geometry.parts)):  # the deflection rows of the part properties
        project.update_part(index, **part_ops.retessellate(project, index, LINEAR_DEFLECTION, ANGULAR_DEFLECTION))
    project.update_domain(**{1: DOMAIN, 2: DOMAIN_R2, 3: DOMAIN_R3}[round_])
    project.update_physics(nu=NU)
    project.update_inflow(speed=SPEED, turbulence_intensity=TURBULENCE_INTENSITY)
    project.update_reports(reference_area_basis="custom", reference_area=A_REF_HALF, reference_length=LENGTH)
    if round_ == 1:
        project.update_solver(cores=SOLVER_CORES, iterations=ITERATIONS, write_interval=ITERATIONS,
                              stopping=stopping())
    else:
        project.update_solver(cores=CORES_R2, iterations=ITERATIONS, write_interval=ITERATIONS,
                              stopping=stopping_round2())
        project.update_mesh(cores=CORES_R2)
    project.save()
    return project
