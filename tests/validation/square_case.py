"""The square cylinder at Re 22,000, URANS k-omega SST in 2D (docs/validation/square_re22000/SETUP.md; ERCOFTAC
UFR 2-02): the section generated by code and the app project set up for it (2D mode, transient). No Qt.

The square of side D = 1 m is imported as a 2D section (a closed polygon written as a Selig file, the app's airfoil
import, D-121). Re = U D / nu = 22,000 with U = 1 m/s: the flow-through time t_c = D / U is 1 s.
"""

import math
from pathlib import Path

import numpy as np

SIDE = 1.0
SPEED = 1.0
NU = 1.0 / 22000.0  # Re = 22,000
RE = SPEED * SIDE / NU
INTENSITY = 0.02  # the experiment's approach-flow turbulence, about 2 % (ERCOFTAC UFR 2-02)

# The domain (SETUP.md): the "2D airfoil" preset's C-type far field, 20 D ahead and to each side, the wake 30 D.
RADIUS = 20.0
WAKE = 30.0

# Two mesh levels (SETUP.md, "Mesh"): the background cell (m); every refinement level is kept, so every cell
# scales with it (ratio sqrt(2)). The walls: the app's default y+ sizing (target 50, wall functions).
LEVELS = {"coarse": math.sqrt(2.0), "medium": 1.0}
SURFACE_LEVEL = 7  # the surface cell: base / 128
WAKE_LEVEL_SIZE = 1.0 / 16.0  # the wake box's target size per metre of background cell
WAKE_BOX = ((7.0, 0.0, 0.0), (15.0, 1.0, 5.0))  # centre and size: x from -0.5 D to 14.5 D, 5 D high

END_TIME = 200.0  # t_c
WINDOW = 20.0  # t_c
CORES = 4

# The references and the pass rule (SETUP.md, written before the runs): ERCOFTAC UFR 2-02 (Lyn et al. 1995).
ST_REFERENCE = 0.133  # St 0.133 +- 0.004 (measured)
ST_TOLERANCE = 0.10
CD_REFERENCE = 2.1  # mean Cd about 2.1, deduced from the wake's velocity distribution (not measured)
CD_TOLERANCE = 0.15


def square_selig(per_side: int = 120) -> str:
    """The square (x from 0 to D, y from -D/2 to D/2) in the Selig order: from (D, 0) up the rear face, along the
    top to the front face, down it, along the bottom and up the rear face back to (D, 0); sharp corners."""
    h = 0.5 * SIDE
    corners = [(SIDE, 0.0), (SIDE, h), (0.0, h), (0.0, -h), (SIDE, -h), (SIDE, 0.0)]
    counts = [per_side // 2, per_side, per_side, per_side, per_side // 2]
    rows = []
    for (x0, y0), (x1, y1), n in zip(corners, corners[1:], counts):
        for s in np.linspace(0.0, 1.0, n, endpoint=False):
            rows.append((x0 + s * (x1 - x0), y0 + s * (y1 - y0)))
    rows.append(corners[-1])
    return "Square cylinder D = 1 (Selig order)\n" + "\n".join(f"{x:.10f} {y:.10f}" for x, y in rows) + "\n"


def verdict(st: float | None, cd_mean: float | None) -> tuple[str, dict]:
    """(PASS / FAIL, the errors): St within 10 % of 0.133 and the mean Cd within 15 % of 2.1."""
    if st is None or cd_mean is None:
        return "FAIL", {}
    errors = {"st": (st - ST_REFERENCE) / ST_REFERENCE, "cd": (cd_mean - CD_REFERENCE) / CD_REFERENCE}
    ok = abs(errors["st"]) <= ST_TOLERANCE and abs(errors["cd"]) <= CD_TOLERANCE
    return ("PASS" if ok else "FAIL"), errors


def build_project(folder: Path, level: str = "coarse", end_time: float = END_TIME, cores: int = CORES,
                  **transient_settings):
    """The project in ``folder`` (created): the "2D airfoil" preset, k-omega SST transient at Re 22,000, the square
    imported as a section, the domain, the level's mesh and the wake box; the app's transient defaults (PIMPLE at
    Co 2, the start-up perturbation, the detected sampling start) unless ``transient_settings`` say otherwise."""
    from vortexcfd.core.model import BoxShape, RefinementVolume
    from vortexcfd.core.presets import BUILTIN_PRESETS, apply_preset
    from vortexcfd.core.project import Project
    from vortexcfd.workflow import part_ops

    base = LEVELS[level]
    folder = Path(folder)
    (folder / "geometry").mkdir(parents=True, exist_ok=True)
    project = Project.new(f"square_{level}")
    project._sim = apply_preset(project.sim, next(p for p in BUILTIN_PRESETS if p.name == "2D airfoil"))
    project.update_physics(nu=NU, flow="incompressible_transient", turbulence_model="kOmegaSST")
    project.update_inflow(speed=SPEED, turbulence_intensity=INTENSITY)
    project.update_reports(reference_length=SIDE, center_of_rotation=(0.5 * SIDE, 0.0, 0.0))
    project.update_domain(radius=RADIUS, downstream=WAKE)
    project.update_mesh(base_size=base, surface_level_min=SURFACE_LEVEL, surface_level_max=SURFACE_LEVEL)
    project.update_solver(cores=cores, live_view=False)
    project.update_transient(end_time=end_time, write_interval=end_time, window=WINDOW, **transient_settings)
    centre, size = WAKE_BOX
    project._sim = project.sim.model_copy(update={"refinement_volumes": [RefinementVolume(
        id="wake", name="Wake", shape=BoxShape(centre=centre, size=size), target_size=WAKE_LEVEL_SIZE * base,
        frame="wind")]})
    project.save(folder / "square.json")
    dat = folder / "square.dat"
    dat.write_text(square_selig(), encoding="utf-8")
    project.add_part(part_ops.airfoil_part(folder, dat, "square", set(), closure="sharp"))
    project.save()
    return project
