EXPECTED_METHOD = {"holes": "pymeshfix", "flipped patch": "pymeshfix", "duplicated faces": "pymeshfix",
                   "self-intersection": "pytetwild envelope"}


@pytest.mark.parametrize("defect", list(BROKEN))
def test_each_broken_surface_is_repaired(defect: str) -> None:
    broken = BROKEN[defect]()
    assert not check_surface(broken).snappy_ready
    result = repair.repair_surface(broken)
    assert result.method == EXPECTED_METHOD[defect]
    assert result.after.snappy_ready and result.remaining == [], result.notes
    assert result.after.signed_volume > 0  # outward normals
    assert repair.faithful(broken, result.mesh)[0]
    assert broken.n_cells == BROKEN[defect]().n_cells  # the input is not modified


def test_clean_surface_needs_no_repair() -> None:
    result = repair.repair_surface(pv.Sphere().clean())
    assert result.method == "none" and result.notes == ["The surface needs no repair."]


def test_pymeshfix_losing_geometry_falls_back_to_the_envelope(tmp_path, monkeypatch) -> None:
    monkeypatch.chdir(tmp_path)
    result = repair.repair_surface(BROKEN["self-intersection"]())
    assert result.notes[0].startswith("pymeshfix: the bounding box changed by")
    assert result.mesh.bounds[1] == pytest.approx(0.8, abs=0.01)  # both spheres kept
    assert 0.7 < result.after.signed_volume < 0.76  # their union (0.752 m3 exactly)
    assert list(tmp_path.iterdir()) == []  # no fTetWild debug file left behind


def test_a_defect_that_remains_is_reported(monkeypatch) -> None:
    sphere = pv.Sphere().clean()
    open_sphere = sphere.extract_cells(np.arange(10, sphere.n_cells)).extract_surface(algorithm=None)
    monkeypatch.setattr(repair, "meshfix", lambda mesh: mesh)
    monkeypatch.setattr(repair, "envelope", lambda mesh: mesh)
    result = repair.repair_surface(open_sphere)
    assert result.method == "pytetwild envelope" and not result.after.snappy_ready
    assert result.remaining and result.remaining[0].endswith("open edges")
    assert result.notes[0].startswith("pymeshfix: ") and "open edges" in result.notes[0]


