def test_repair_writes_a_new_version_and_is_one_undo_step(project: Project) -> None:
    geometry = project.path.parent / "geometry"
    holes = sphere_with_holes()
    holes.points *= 1000  # millimetres
    holes.save(str(geometry / "ball.stl"))
    project.add_part(Part(name="Ball", source_file="geometry/ball.stl", units="mm"))
    fields, result = part_ops.repair_part(project, 0)
    assert fields == {"source_file": "geometry/ball_repaired.stl"} and result.method == "pymeshfix"
    project.update_part(0, **fields)
    assert (geometry / "ball.stl").is_file()  # the original stays
    report = surface_report(geometry / "ball_repaired.stl", "mm")
    assert report.snappy_ready and report.size == pytest.approx((1.0, 1.0, 1.0), rel=0.02)  # still in mm
    # A second repair of the repaired version gets its own name.
    project.update_part(0, source_file="geometry/ball.stl")
    assert part_ops.repair_part(project, 0)[0]["source_file"] == "geometry/ball_repaired_2.stl"
    project.undo()
    project.undo()
    assert project.sim.geometry.parts[0].source_file == "geometry/ball.stl"


def test_repair_keeps_the_regions(project: Project) -> None:
    geometry = project.path.parent / "geometry"
    faces = box_faces(resolution=3)
    path = write_multi_solid(geometry / "box.stl", faces[:5])  # the zmax side is missing: a hole
    names = [n for n, _ in faces[:5]]
    project.add_part(part_ops.part_with_solid_regions(project.path.parent, "Box", path, "m", names))
    fields, result = part_ops.repair_part(project, 0)
    assert result.after.snappy_ready and set(fields) == {"source_file", "region_ids"}
    project.update_part(0, **fields)
    part = project.sim.geometry.parts[0]
    mesh = load_surface(project.path.parent / part.source_file, "m")
    ids = regions.read_ids(project.path.parent / part.region_ids, mesh.n_cells)
    centres = mesh.cell_centers().points
    assert set(ids[centres[:, 0] < 1e-6]) == {0} and set(ids[centres[:, 2] < 1e-6]) == {4}  # xmin, zmin
    assert (np.bincount(ids)[:4] >= 18).all()  # every side kept its triangles


